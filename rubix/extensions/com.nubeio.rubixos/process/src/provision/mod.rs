//! Barcode / scan-to-dashboard provisioning (BARCODE.md).
//!
//! Self-contained, `bc_*`-scoped feature: decode a sticker into an
//! identity, look the device up in a YAML template, and CRUD the
//! catalog rows (device + points + widgets + alarms) that make it
//! show on a dashboard, trending and alarming. Deleting this module +
//! the `bc_*` manifest entries removes the feature wholesale
//! (BARCODE.md §11).
//!
//! Module layout follows one-verb-per-file (FILE-LAYOUT.md):
//!  - [`decode`] — barcode string → [`identity::ScannedIdentity`].
//!  - [`template`] / [`template_store`] — YAML parse, expand, persist.
//!  - [`placement`] — resolve/create site, location, page.
//!  - [`points`] / [`alarms`] / [`widgets`] — template → catalog rows.
//!  - [`device`] — device row build, update, decommission.
//!  - [`orchestrate`] — `bc_provision`, tying the above together.
//!  - [`label`] — printable label render.
//!  - [`crud`] / [`ids`] — shared write helpers and id minting.

