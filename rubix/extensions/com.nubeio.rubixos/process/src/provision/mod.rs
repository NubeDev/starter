// The capability bundle generated by `requires!` in `extension.rs`.
// Re-exported here so the verb modules can name `crate::provision::RubixOsCtx`.
pub use crate::extension::RubixOsCtx;

/// `bc_decode` — barcode → identity + resolved template summary.
/// Pure of provisioning side effects; it only *reads* templates to
/// resolve the model.
pub fn handle_decode(ctx: &RubixOsCtx, params: &Value) -> starter_ext_sdk::Result<Value> {
    let barcode = crud::take_str(params, "barcode", "bc_decode")?;
    let identity = decode::decode(&barcode)?;
    let known = template_store::known_models(ctx);
    // Resolve the template if known; otherwise return identity with an
    // empty template + the known-models list (friendly, never a 500).
    let template_summary = match template_store::load(ctx, &identity.model) {
        Ok(tpl) => tpl.decode_summary(),
        Err(_) => json!(null),
    };
    Ok(identity.to_decode_output(template_summary, known))
}

