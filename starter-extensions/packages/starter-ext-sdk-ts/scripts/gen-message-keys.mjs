// Regenerate `src/message-keys.generated.ts` from the canonical
// platform catalog (`crates/starter-i18n/catalogs/starter/en.json`).
//
// Why a script rather than a typed `Object.keys` at runtime: the
// `MessageKey` union is a *type*, not a value, so it has to be
// materialised before TypeScript reads it. Running this in CI (Stage
// 5 catalog-parity gate) keeps the generated union in lockstep with
// the catalog without forcing every extension author to bundle the
// catalog JSON as a build-time import.
//
// Usage: `node scripts/gen-message-keys.mjs` from the SDK directory,
// or `pnpm --filter @nube/starter-ext-sdk-ts gen-keys` from the
// workspace root. Re-runs are deterministic — the script writes a
// banner with the source path and a sorted union so diffs only
// surface actual catalog changes.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..", "..", "..");
const catalogPath = resolve(repoRoot, "crates/starter-i18n/catalogs/starter/en.json");
const outPath = resolve(here, "..", "src", "message-keys.generated.ts");

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const keys = Object.keys(catalog).sort();

const lines = [];
lines.push("// AUTOGENERATED by scripts/gen-message-keys.mjs — DO NOT EDIT BY HAND.");
lines.push("//");
lines.push("// Source: crates/starter-i18n/catalogs/starter/en.json");
lines.push("//");
lines.push("// The `MessageKey` shipped from `./message-keys.js` is the union of");
lines.push("// this generated `PlatformMessageKey` plus any extension-declared");
lines.push("// key (free-form `string & {}` so a typo in an extension catalog");
lines.push("// still resolves to react-intl's id-fallback, while platform keys");
lines.push("// get autocomplete + typo-as-error). The Stage 5 catalog-parity CI");
lines.push("// gate re-runs this script and fails if the output drifts.");
lines.push("");
lines.push("/** Every key shipped in the platform `en` catalog. */");
lines.push("export type PlatformMessageKey =");
keys.forEach((k, i) => {
  const sep = i === keys.length - 1 ? ";" : "";
  lines.push(`  | ${JSON.stringify(k)}${sep}`);
});
lines.push("");

writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${keys.length} platform message keys to ${outPath}`);
